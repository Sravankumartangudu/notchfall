import AppKit
import SwiftUI

/// 📋 Something that was copied: text, a picture or files.
struct Clip: Identifiable {
    enum Kind { case text(String), image(NSImage), files([URL]) }
    let id = UUID()
    let kind: Kind
    let app: String?          // the app it was copied from, by name
    let at: Date

    var title: String {
        switch kind {
        case .text(let s):
            let line = s.split(whereSeparator: \.isNewline).first.map(String.init) ?? s
            return line.trimmingCharacters(in: .whitespaces)
        case .image(let i): return "Image · \(Int(i.size.width))×\(Int(i.size.height))"
        case .files(let urls): return urls.count == 1 ? urls[0].lastPathComponent : "\(urls.count) files"
        }
    }

    var symbol: String {
        switch kind {
        case .text(let s): return s.hasPrefix("http://") || s.hasPrefix("https://") ? "link" : "text.alignleft"
        case .image: return "photo"
        case .files: return "doc.on.doc"
        }
    }
}

/// Keeps the last few things you copied, so ⌃⌥V can bring one back. Held in memory only, never written
/// anywhere, and cleared when the app quits. Passwords and other secrets are skipped: password managers
/// mark what they copy as concealed or transient (the nspasteboard.org convention), and those are ignored.
final class Clipboard {
    private(set) var clips: [Clip] = []
    static let limit = 20
    var enabled = false
    var onChange: () -> Void = {}

    /// Newer macOS versions ask before an app reads the clipboard on its own. "Don't allow" means the
    /// history can't work, so it stops reading rather than asking again.
    static var denied: Bool {
        if #available(macOS 15.4, *) { return NSPasteboard.general.accessBehavior == .alwaysDeny }
        return false
    }
    static var asks: Bool {
        if #available(macOS 15.4, *) { return NSPasteboard.general.accessBehavior != .alwaysAllow }
        return false
    }
    /// Images bigger than this (in pixels) aren't kept: twenty photos would take hundreds of MB.
    private static let maxPixels = 4096 * 4096

    private let board = NSPasteboard.general
    private var seen: Int
    private var timer: Timer?

    private static let secret: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                              "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                                              "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
                                              "Pasteboard generator type"]

    init() { seen = board.changeCount }

    func start() {
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        guard board.changeCount != seen else { return }
        seen = board.changeCount
        guard enabled, !Self.denied, let types = board.types, !types.contains(where: { Self.secret.contains($0.rawValue) }) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        var kind: Clip.Kind?
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            kind = .files(urls)
        } else if types.contains(.png) || types.contains(.tiff), let img = NSImage(pasteboard: board) {
            let px = img.representations.map { $0.pixelsWide * $0.pixelsHigh }.max() ?? 0
            guard px <= Self.maxPixels else { return }
            kind = .image(img)
        } else if let s = board.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            kind = .text(s)
        }
        guard let kind else { return }
        add(Clip(kind: kind, app: app, at: Date()))
    }

    func add(_ c: Clip) {
        // Copying the same text again moves it to the top instead of adding a twin.
        if case .text(let s) = c.kind {
            clips.removeAll { if case .text(let t) = $0.kind { return t == s }; return false }
        }
        clips = Array(([c] + clips).prefix(Self.limit))
        onChange()
    }

    /// Puts a clip back on the clipboard, ready for ⌘V. It doesn't count as a new copy.
    func copy(_ c: Clip) {
        board.clearContents()
        switch c.kind {
        case .text(let s): board.setString(s, forType: .string)
        case .image(let i): board.writeObjects([i])
        case .files(let urls): board.writeObjects(urls as [NSURL])
        }
        seen = board.changeCount
        clips.removeAll { $0.id == c.id }
        clips.insert(Clip(kind: c.kind, app: c.app, at: c.at), at: 0)
        onChange()
    }

    func clear() {
        clips = []
        onChange()
    }

    /// Made-up clips for previews and screenshots.
    /// A made-up sunset for the screenshots: sky, sun and hills.
    private static let demoPhoto = NSImage(size: NSSize(width: 1600, height: 1000), flipped: false) { r in
        NSGradient(colors: [NSColor(red: 0.98, green: 0.62, blue: 0.36, alpha: 1), NSColor(red: 0.42, green: 0.36, blue: 0.75, alpha: 1)])?.draw(in: r, angle: 90)
        NSColor(red: 1, green: 0.88, blue: 0.55, alpha: 1).setFill()
        NSBezierPath(ovalIn: NSRect(x: 1000, y: 380, width: 260, height: 260)).fill()
        NSColor(red: 0.2, green: 0.17, blue: 0.38, alpha: 1).setFill()
        let hills = NSBezierPath()
        hills.move(to: .zero)
        hills.curve(to: NSPoint(x: 1600, y: 260), controlPoint1: NSPoint(x: 500, y: 620), controlPoint2: NSPoint(x: 1100, y: 80))
        hills.line(to: NSPoint(x: 1600, y: 0))
        hills.close()
        hills.fill()
        return true
    }

    static func demo() -> [Clip] {
        let now = Date()
        return [
            Clip(kind: .text("https://github.com/Sravankumartangudu/notchfall"), app: "Safari", at: now.addingTimeInterval(-40)),
            Clip(kind: .text("Let's move the design review to Thursday at 3?"), app: "Messages", at: now.addingTimeInterval(-300)),
            Clip(kind: .image(demoPhoto), app: "Preview", at: now.addingTimeInterval(-900)),
            Clip(kind: .files([URL(fileURLWithPath: "/tmp/notchfall-demo/Q3 Roadmap.key")]), app: "Finder", at: now.addingTimeInterval(-1800)),
            Clip(kind: .text("git push origin main"), app: "Terminal", at: now.addingTimeInterval(-3600)),
            Clip(kind: .text("Flight UA 837 · gate G92 · boards 10:25"), app: "Mail", at: now.addingTimeInterval(-7200)),
        ]
    }
}

/// ⌃⌥V: the clipboard history drops out of the notch. Click one to copy it back, then ⌘V.
struct ClipsContent: View {
    @ObservedObject var m: IslandModel
    let inset: CGFloat
    static let rows = 5
    static let rowHeight: CGFloat = 40

    var body: some View {
        let on = m.showContent
        let tint = rgb(0.55, 0.78, 1)
        VStack(spacing: 0) {
            Wings(m: m) {
                HStack(spacing: 6) {
                    Image(systemName: "list.clipboard.fill").font(.system(size: 10, weight: .bold))
                    Text("CLIPBOARD").kerning(0.6)
                }
                .font(.system(size: 11, weight: .bold, design: .rounded))
                .foregroundStyle(tint)
                .reveal(on, 0.02)
            } right: {
                Text(m.clips.isEmpty ? "Nothing yet" : "Click to copy")
                    .font(.system(size: 12, weight: .semibold, design: .rounded))
                    .foregroundStyle(.white.opacity(0.55))
                    .reveal(on, 0.04)
            }
            .padding(.horizontal, 6)

            if m.clips.isEmpty {
                HStack(spacing: 12) {
                    Image(systemName: "doc.on.clipboard").font(.system(size: 20)).foregroundStyle(tint)
                    VStack(alignment: .leading, spacing: 2) {
                        Text("Copy something").font(.system(size: 14, weight: .semibold, design: .rounded)).foregroundStyle(.white)
                        Text("The last \(Clipboard.limit) things you copy show up here. Kept in memory only.")
                            .font(.system(size: 11.5, design: .rounded)).foregroundStyle(.white.opacity(0.5))
                    }
                    Spacer()
                }
                .padding(.top, 12)
                .padding(.horizontal, 6)
                .reveal(on, 0.06)
            } else {
                ScrollView(.vertical, showsIndicators: false) {
                    VStack(spacing: 2) {
                        ForEach(Array(m.clips.enumerated()), id: \.element.id) { i, c in
                            ClipRow(m: m, clip: c, tint: tint).reveal(on, 0.05 + Double(min(i, 6)) * 0.04)
                        }
                    }
                }
                .frame(height: CGFloat(min(Self.rows, m.clips.count)) * (Self.rowHeight + 2))
                .padding(.top, 8)
            }
            Spacer(minLength: 0)
        }
        .padding(.horizontal, inset - 6)
    }
}

private struct ClipRow: View {
    @ObservedObject var m: IslandModel
    let clip: Clip
    let tint: Color
    @State private var hover = false

    var body: some View {
        HStack(spacing: 11) {
            Group {
                switch clip.kind {
                case .image(let img):
                    Image(nsImage: img).resizable().aspectRatio(contentMode: .fill)
                        .frame(width: 28, height: 28).clipShape(RoundedRectangle(cornerRadius: 6, style: .continuous))
                case .files(let urls):
                    Image(nsImage: Shelf.icon(urls[0])).resizable().frame(width: 26, height: 26)
                case .text:
                    Image(systemName: clip.symbol).font(.system(size: 12, weight: .semibold)).foregroundStyle(tint)
                        .frame(width: 28, height: 28).background(Circle().fill(tint.opacity(0.15)))
                }
            }
            VStack(alignment: .leading, spacing: 1) {
                Text(clip.title)
                    .font(.system(size: 13, weight: .medium, design: .rounded))
                    .foregroundStyle(.white)
                    .lineLimit(1)
                    .truncationMode(.tail)
                Text([clip.app, clip.at.formatted(.relative(presentation: .named))].compactMap { $0 }.joined(separator: "  ·  "))
                    .font(.system(size: 10.5, design: .rounded))
                    .foregroundStyle(.white.opacity(0.45))
            }
            Spacer(minLength: 6)
            if hover {
                Image(systemName: "doc.on.doc.fill").font(.system(size: 11, weight: .bold)).foregroundStyle(tint)
            }
        }
        .padding(.horizontal, 8)
        .frame(height: ClipsContent.rowHeight)
        .background(RoundedRectangle(cornerRadius: 12, style: .continuous).fill(.white.opacity(hover ? 0.08 : 0)))
        .contentShape(Rectangle())
        .onHover { h in withAnimation(.easeOut(duration: 0.12)) { hover = h } }
        .onTapGesture { m.onClip(clip) }
    }
}
